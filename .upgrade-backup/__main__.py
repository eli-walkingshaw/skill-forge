def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="forge", description="Self-updating Claude skill builder")
    sub = p.add_subparsers(dest="cmd", required=True)

    sub.add_parser("init", help="Set up vault + skills repo folders").set_defaults(fn=cmd_init)
    sub.add_parser("scan", help="Pull captures from configured sources").set_defaults(fn=cmd_scan)
    sub.add_parser("cluster", help="Cluster captures into skill candidates").set_defaults(fn=cmd_cluster)

    draft_p = sub.add_parser("draft", help="Draft SKILL.md for new clusters")
    draft_p.add_argument("cluster_id", nargs="?", help="Specific cluster id (default: all new)")
    draft_p.set_defaults(fn=cmd_draft)

    sub.add_parser("run", help="scan → cluster → draft (cron target)").set_defaults(fn=cmd_run)
    sub.add_parser("watch", help="Daemon: sync approved/ to git").set_defaults(fn=cmd_watch)
    sub.add_parser("status", help="Show pipeline state").set_defaults(fn=cmd_status)
    sub.add_parser("install-cron", help="Print crontab line to install").set_defaults(fn=cmd_install_cron)

    return p


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        config = load_config()
    except RuntimeError as e:
        print(f"config error: {e}", file=sys.stderr)
        print("Tip: copy .env.example to .env and fill it in.", file=sys.stderr)
        return 2
    return args.fn(args, config)


if __name__ == "__main__":
    sys.exit(main())
